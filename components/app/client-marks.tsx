export function InlineClientMark({
  logoPath,
  size,
  color,
  style,
}: {
  logoPath: string;
  size: number;
  color: string;
  style?: CSSProperties;
}) {
  const mark = CLIENT_MARKS[logoPath];
  if (!mark) return null;

  return (
    <svg
      width={Math.round(size * mark.aspect)}
      height={size}
      viewBox={mark.viewBox}
      aria-hidden
      style={{ color, flexShrink: 0, ...style }}
    >
      <g fill="currentColor">
        {mark.paths.map((d, i) => (
          <path key={i} d={d} />
        ))}
      </g>
    </svg>
  );
}
