import { expect, test } from "./fixtures";

/**
 * The installed app, and the three things that made it a dead end.
 *
 *  - `start_url` was `/`. Install to the Home Screen, tap the icon, land on the
 *    marketing page — which contained **no link to `/app` at all** — and there
 *    is no address bar inside an installed app to type one into.
 *  - `background_color` and `theme_color` were `#07090E`, which is the DARK
 *    canvas. Light is the default theme, so every launch flashed the wrong
 *    colour before the first paint.
 *  - `viewport-fit` was never set, so **every `env(safe-area-inset-*)` in this
 *    codebase resolved to zero** — the rail, the topbar and the dialog shell
 *    had all been padding themselves against a notch that, as far as the layout
 *    engine was concerned, did not exist.
 */

/** An iPhone 15's insets, portrait: the notch above, the home indicator below. */
const NOTCH = { top: 59, bottom: 34, left: 0, right: 0 };
/** Landscape, where the left and right insets are the ones that bite. */
const NOTCH_LANDSCAPE = { top: 0, bottom: 21, left: 59, right: 59 };

test.describe("the manifest", () => {
  test("is served, parses, and starts the app rather than the brochure", async ({ page }) => {
    const response = await page.request.get("/site.webmanifest");
    expect(response.status()).toBe(200);

    const manifest = JSON.parse(await response.text());

    expect(manifest.start_url, "installing must land on the app").toBe("/app");
    // `id` is what a browser uses to decide whether an install is the SAME app.
    // Without it the id defaults to `start_url`, so changing the start URL later
    // would look like a different application and orphan every install.
    expect(manifest.id).toBe("/app");
    // Scope stays whole-site: one manifest, and a link from `/` back into the
    // app must not leave the installed window.
    expect(manifest.scope).toBe("/");
    expect(manifest.display).toBe("standalone");

    // Light is the default theme — a reversed ADR, recorded in 05-DECISIONS.md.
    // These two are the splash screen, painted before any CSS runs.
    expect(manifest.background_color, "the splash is the dark canvas").toBe("#ebeff6");
    expect(manifest.theme_color).toBe("#ebeff6");

    const shortcuts = (manifest.shortcuts ?? []).map((s: { url: string }) => s.url);
    expect(shortcuts).toContain("/app/my-work");
    expect(shortcuts).toContain("/app/settings");

    // Generated by `npm run brand:assets` and not to be hand-edited — the
    // assertion is that they are still all there and still resolve.
    expect(manifest.icons.length).toBeGreaterThanOrEqual(3);
    expect(
      manifest.icons.some((icon: { purpose?: string }) => icon.purpose === "maskable"),
      "no maskable icon — Android will letterbox it"
    ).toBe(true);

    for (const icon of manifest.icons as Array<{ src: string }>) {
      const asset = await page.request.get(icon.src);
      expect(asset.status(), `${icon.src} is missing`).toBe(200);
    }
  });

  test("the document links to it, and declares viewport-fit=cover", async ({ page }) => {
    await page.goto("/");

    await expect(page.locator('link[rel="manifest"]')).toHaveAttribute("href", "/site.webmanifest");

    // The one that makes every `env(safe-area-inset-*)` in the codebase mean
    // something. Read off the rendered meta rather than off `viewport.ts`,
    // because what matters is what the document says.
    const content = await page.locator('meta[name="viewport"]').getAttribute("content");
    expect(content, "no viewport meta").not.toBeNull();
    expect(content, "viewport-fit=cover is missing — every inset resolves to 0").toContain(
      "viewport-fit=cover"
    );

    // And deliberately NOT these: `e2e/a11y.spec.ts` asserts no horizontal
    // overflow at 200% zoom, and a viewport that cannot be zoomed fails WCAG
    // 1.4.4 whatever it does for the layout.
    expect(content).not.toContain("maximum-scale");
    expect(content).not.toContain("user-scalable=no");
  });
});

test.describe("the way in", () => {
  for (const width of [390, 1440]) {
    test(`the marketing site links to the app at ${width}px`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 });
      await page.goto("/");

      // Present in the DOM and visible without opening anything. At 390px the
      // label collapses to the arrow, which is why this locates by href.
      const link = page.locator('header a[href="/app"]').first();
      await expect(link, `no visible link to /app at ${width}px`).toBeVisible();

      const box = await link.boundingBox();
      expect(box!.width, "44px target").toBeGreaterThanOrEqual(44);
      expect(box!.height, "44px target").toBeGreaterThanOrEqual(44);
    });
  }

  test("one link serves a signed-out and a signed-in visitor", async ({ page }) => {
    // `middleware.ts` does the deciding, which is why there is one link rather
    // than two and no client-side "are you signed in" check on the brochure.
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto("/");
    await page.locator('header a[href="/app"]').first().click();
    await expect(page).toHaveURL(/\/login\?next=%2Fapp/);
  });

  test("and it takes a signed-in visitor straight into the app", async ({ adminPage: page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto("/");
    await page.locator('header a[href="/app"]').first().click();
    await expect(page).toHaveURL(/\/app\/projects\/.+\/sprints\/\d+$/);
  });
});

test.describe("the safe area, with a notch emulated", () => {
  // `Emulation.setSafeAreaInsetsOverride` is a CDP method, and CDP is Chromium.
  // Running this on WebKit would mean asserting the insets it happens to have,
  // which on a headless build is nothing at all — a test that passes by
  // measuring zero against zero.
  test.skip(
    ({ browserName }) => browserName !== "chromium",
    "safe-area emulation is CDP, and CDP is Chromium-only"
  );

  /**
   * `Emulation.setSafeAreaInsetsOverride` sets the insets DIRECTLY, so it does
   * not go through `viewport-fit` — which means this test would pass even with
   * `viewport-fit` unset, and on its own it proves only that the CSS consumes
   * an inset it is given. The `viewport-fit=cover` assertion above is the other
   * half, and neither is worth much without the other.
   */
  async function emulate(
    page: import("@playwright/test").Page,
    insets: { top: number; bottom: number; left: number; right: number }
  ) {
    const client = await page.context().newCDPSession(page);
    await client.send("Emulation.setSafeAreaInsetsOverride" as never, { insets } as never);
  }

  test("the rail and the topbar clear the notch", async ({ adminPage: page }) => {
    await page.setViewportSize({ width: 900, height: 600 });
    await emulate(page, NOTCH_LANDSCAPE);
    await page.goto("/app/projects/meinevim/sprints/17");

    const railLeft = await page
      .getByRole("complementary")
      .evaluate((el) => parseFloat(getComputedStyle(el).paddingLeft));
    expect(railLeft, "the rail sits under the rounded corner").toBeGreaterThanOrEqual(59);

    const topbarRight = await page
      .getByRole("banner")
      .evaluate((el) => parseFloat(getComputedStyle(el).paddingRight));
    expect(topbarRight, "the topbar's controls sit under the corner").toBeGreaterThanOrEqual(59);
  });

  test("a dialog clears the home indicator", async ({ adminPage: page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await emulate(page, NOTCH);
    await page.goto("/app/projects/meinevim/sprints/17");

    await page.getByRole("link", { name: "Add optional titles to all webparts" }).click();
    await expect(page.getByRole("dialog")).toBeVisible();

    const scrimBottom = await page
      .locator("[data-scrim]")
      .evaluate((el) => parseFloat(getComputedStyle(el).paddingBottom));
    expect(scrimBottom, "the dialog runs under the home indicator").toBeGreaterThanOrEqual(34);
  });

  test("without a notch the insets cost nothing", async ({ adminPage: page }) => {
    // The other half of the claim: `max()` against a zero inset must not add
    // padding on a screen that has no notch.
    await page.setViewportSize({ width: 900, height: 600 });
    await emulate(page, { top: 0, bottom: 0, left: 0, right: 0 });
    await page.goto("/app/projects/meinevim/sprints/17");

    const railLeft = await page
      .getByRole("complementary")
      .evaluate((el) => parseFloat(getComputedStyle(el).paddingLeft));
    expect(railLeft).toBe(12);
  });
});
