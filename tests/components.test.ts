import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import {
  COMPONENT_KINDS,
  COMPONENT_KIND_HINT,
  COMPONENT_KIND_LABEL,
  COMPONENT_KIND_TONE,
  COMPONENT_TAG_ORDER,
  componentSlug,
  componentsFromTags,
  matchesComponentFilter,
  orderComponentTags,
  parseComponentFilter,
  parseComponentMatch,
  type ComponentKind,
  type ComponentTag,
} from "@/lib/components";


/**
 * The component vocabulary is defined twice — once in Postgres, once in
 * TypeScript — for the same reason the status vocabulary is, and with the same
 * risk. These read the SQL text rather than the database so they fail in CI on
 * a machine with no Postgres.
 *
 * The slug tests matter more than they look. The column carries
 * `check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')`, and the generator that writes
 * the seed has its OWN copy of this function — three places that have to agree
 * about "EVIM Heading & Separator", in a project where half the names are
 * German.
 */
const MIGRATION = join(process.cwd(), "supabase", "migrations", "20260824120000_components.sql");
const SEED = join(process.cwd(), "supabase", "seeds", "components.sql");

/** The column's own constraint, restated. If this changes, the test should fail. */
const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

describe("component vocabulary", () => {
  it("SQL and TypeScript agree on the enum members", () => {
    const sql = readFileSync(MIGRATION, "utf8");
    const declaration = sql.slice(
      sql.indexOf("create type component_kind"),
      sql.indexOf("comment on type component_kind")
    );
    const inSql = [...declaration.matchAll(/'(\w+)'/g)].map(([, kind]) => kind as ComponentKind);

    expect(inSql).toEqual([...COMPONENT_KINDS]);
  });

  it("every kind has a label, a hint and a tone", () => {
    for (const kind of COMPONENT_KINDS) {
      expect(COMPONENT_KIND_LABEL[kind], kind).toBeTruthy();
      expect(COMPONENT_KIND_HINT[kind], kind).toBeTruthy();
      expect(COMPONENT_KIND_TONE[kind], kind).toBeTruthy();
    }
  });
});

describe("componentSlug", () => {
  it("produces something the column's check constraint accepts", () => {
    for (const name of [
      "EVIM Themen Kachel",
      "EVIM Heading & Separator",
      "EVIM Process & Timeline",
      "News-Redaktion",
      "  spaced   out  ",
      "Tabs 2.0",
    ]) {
      expect(componentSlug(name), name).toMatch(SLUG_PATTERN);
    }
  });

  it("folds German rather than dropping it", () => {
    // "Überschrift" losing its first letter would still be a valid slug, which
    // is exactly why this is asserted: the failure looks like success.
    expect(componentSlug("Überschrift")).toBe("uberschrift");
    expect(componentSlug("Größe")).toBe("grosse");
    expect(componentSlug("Änderung")).toBe("anderung");
  });

  it("spells & as `and`, so two names cannot collide on a hyphen", () => {
    expect(componentSlug("Heading & Separator")).toBe("heading-and-separator");
    // Without the `&` rule both of these would be "heading-separator".
    expect(componentSlug("Heading Separator")).not.toBe(componentSlug("Heading & Separator"));
  });

  it("returns nothing when nothing can survive, rather than an invalid slug", () => {
    // The caller must treat this as invalid input. Sending "" to the database
    // would be answered by a check constraint, in Postgres' words, not ours.
    expect(componentSlug("!!!")).toBe("");
    expect(componentSlug("   ")).toBe("");
  });
});

describe("the generated registry", () => {
  const seed = readFileSync(SEED, "utf8");
  const rows = [
    ...seed.matchAll(/\('((?:[^']|'')*)'\s*,\s*'([a-z0-9-]+)'\s*,\s*'(react|spfx)'\s*,/g),
  ].map(([, name, slug, kind]) => ({ name: name.replace(/''/g, "'"), slug, kind }));

  it("was generated, and has rows", () => {
    expect(seed).toContain("GENERATED by scripts/sync-evim-components.mjs");
    expect(rows.length).toBeGreaterThan(30);
  });

  it("every slug is the one componentSlug would produce for its name", () => {
    // The seed generator has its own copy of the slug rule. If the two ever
    // disagree, a component added in the app and the same component synced from
    // the delivery repo become two rows, and the history splits in half.
    for (const row of rows) {
      expect(componentSlug(row.name), row.name).toBe(row.slug);
    }
  });

  it("has no duplicate slugs — the table's unique constraint, checked early", () => {
    const seen = new Set(rows.map((row) => row.slug));
    expect(seen.size).toBe(rows.length);
  });
});

/**
 * A story is about more than one component, and the order its chips render in
 * is defined twice: `primary_component_of()` in SQL decides which one the mirror
 * column holds, and `orderComponentTags()` in TypeScript decides which one is
 * drawn first. If those two disagree the table's first chip is not the primary
 * component, which is a lie nobody would notice.
 *
 * Read from the migration text, like every other drift guard here, so it fails
 * on a machine with no Postgres.
 */
describe("component tag ordering", () => {
  const JOIN_MIGRATION = join(
    process.cwd(),
    "supabase",
    "migrations",
    "20260825120000_work_item_components.sql"
  );

  it("SQL and TypeScript agree on the sort key", () => {
    const sql = readFileSync(JOIN_MIGRATION, "utf8");
    const body = sql.slice(
      sql.indexOf("create or replace function public.primary_component_of"),
      sql.indexOf("comment on function public.primary_component_of")
    );

    const clause = /order\s+by\s+([^\n]+)/i.exec(body);
    expect(clause, "primary_component_of must have an explicit order by").not.toBeNull();

    const keys = clause![1]
      .split(",")
      .map((key) => key.trim().replace(/^wc\./, ""))
      .filter(Boolean);

    expect(keys).toEqual([...COMPONENT_TAG_ORDER]);
  });

  it("is total, so the same tags always render in the same sequence", () => {
    // Same position AND same timestamp — the case position alone cannot order,
    // and the one a non-total comparator gets wrong on alternate reloads.
    const tie = (componentId: string): ComponentTag => ({
      position: 0,
      createdAt: "2026-08-25T09:00:00Z",
      componentId,
      component: null,
    });

    const forwards = orderComponentTags([tie("b"), tie("a"), tie("c")]);
    const backwards = orderComponentTags([tie("c"), tie("b"), tie("a")]);

    expect(forwards.map((tag) => tag.componentId)).toEqual(["a", "b", "c"]);
    expect(backwards.map((tag) => tag.componentId)).toEqual(["a", "b", "c"]);
  });

  it("sorts by position first, then by when the tag was added", () => {
    const tags: ComponentTag[] = [
      { position: 0, createdAt: "2026-08-25T10:00:00Z", componentId: "second", component: null },
      { position: -1, createdAt: "2026-08-25T11:00:00Z", componentId: "promoted", component: null },
      { position: 0, createdAt: "2026-08-25T09:00:00Z", componentId: "first", component: null },
    ];

    // `promoted` sorts ahead despite being newest: that is what a write to the
    // old scalar column does — `min(position) - 1` — and the read model has to
    // agree with it or the mirror and the first chip name different components.
    expect(orderComponentTags(tags).map((tag) => tag.componentId)).toEqual([
      "promoted",
      "first",
      "second",
    ]);
  });

  it("drops embeds that came back null rather than rendering a hole", () => {
    const tags: ComponentTag[] = [
      { position: 0, createdAt: "2026-08-25T09:00:00Z", componentId: "a", component: null },
    ];
    expect(componentsFromTags(tags)).toEqual([]);
    expect(componentsFromTags(null)).toEqual([]);
  });
});

describe("the component filter", () => {
  it("defaults to any, including for a link written before match existed", () => {
    expect(parseComponentMatch(null)).toBe("any");
    expect(parseComponentMatch(undefined)).toBe("any");
    expect(parseComponentMatch("")).toBe("any");
    expect(parseComponentMatch("nonsense")).toBe("any");
    expect(parseComponentMatch("all")).toBe("all");
  });

  it("keeps order, drops duplicates, and refuses anything that is not a slug", () => {
    expect(parseComponentFilter("banner,link-kachel,banner")).toEqual(["banner", "link-kachel"]);
    expect(parseComponentFilter(" banner , link-kachel ")).toEqual(["banner", "link-kachel"]);
    expect(parseComponentFilter("Banner")).toEqual([]);
    expect(parseComponentFilter("../../etc/passwd")).toEqual([]);
    expect(parseComponentFilter("a b,c;d")).toEqual([]);
    expect(parseComponentFilter(null)).toEqual([]);
  });

  it("passes everything when nothing is selected", () => {
    // The case a `.every()` over an empty array gets right by accident and a
    // hand-written loop usually gets wrong.
    expect(matchesComponentFilter([], [], "any")).toBe(true);
    expect(matchesComponentFilter([], [], "all")).toBe(true);
    expect(matchesComponentFilter(["banner"], [], "all")).toBe(true);
  });

  it("any is at least one, all is every one", () => {
    const item = ["link-kachel", "tabs-with-cards", "newspart"];

    expect(matchesComponentFilter(item, ["link-kachel"], "any")).toBe(true);
    expect(matchesComponentFilter(item, ["link-kachel", "banner"], "any")).toBe(true);
    expect(matchesComponentFilter(item, ["banner"], "any")).toBe(false);

    expect(matchesComponentFilter(item, ["link-kachel", "tabs-with-cards"], "all")).toBe(true);
    expect(matchesComponentFilter(item, ["link-kachel", "banner"], "all")).toBe(false);

    // An untagged story is in no filtered view but is still in the unfiltered one.
    expect(matchesComponentFilter([], ["link-kachel"], "any")).toBe(false);
    expect(matchesComponentFilter([], ["link-kachel"], "all")).toBe(false);
  });
});
