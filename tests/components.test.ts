import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import {
  COMPONENT_KINDS,
  COMPONENT_KIND_HINT,
  COMPONENT_KIND_LABEL,
  COMPONENT_KIND_TONE,
  componentSlug,
  type ComponentKind,
} from "@/lib/components";

/**
 * The component vocabulary is defined twice — once in Postgres, once in
 * TypeScript — for the same reason the status vocabulary is, and with the same
 * risk. These read the SQL text rather than the database so they fail in CI on
 * a machine with no Postgres.
 *
 * The slug tests matter more than they look. The column carries
 * `check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')`, and the generator that writes
 * the seed has its OWN copy of this function — three places that have to agree
 * about "EVIM Heading & Separator", in a project where half the names are
 * German.
 */
const MIGRATION = join(process.cwd(), "supabase", "migrations", "20260824120000_components.sql");
const SEED = join(process.cwd(), "supabase", "seeds", "components.sql");

/** The column's own constraint, restated. If this changes, the test should fail. */
const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

describe("component vocabulary", () => {
  it("SQL and TypeScript agree on the enum members", () => {
    const sql = readFileSync(MIGRATION, "utf8");
    const declaration = sql.slice(
      sql.indexOf("create type component_kind"),
      sql.indexOf("comment on type component_kind")
    );
    const inSql = [...declaration.matchAll(/'(\w+)'/g)].map(([, kind]) => kind as ComponentKind);

    expect(inSql).toEqual([...COMPONENT_KINDS]);
  });

  it("every kind has a label, a hint and a tone", () => {
    for (const kind of COMPONENT_KINDS) {
      expect(COMPONENT_KIND_LABEL[kind], kind).toBeTruthy();
      expect(COMPONENT_KIND_HINT[kind], kind).toBeTruthy();
      expect(COMPONENT_KIND_TONE[kind], kind).toBeTruthy();
    }
  });
});

describe("componentSlug", () => {
  it("produces something the column's check constraint accepts", () => {
    for (const name of [
      "EVIM Themen Kachel",
      "EVIM Heading & Separator",
      "EVIM Process & Timeline",
      "News-Redaktion",
      "  spaced   out  ",
      "Tabs 2.0",
    ]) {
      expect(componentSlug(name), name).toMatch(SLUG_PATTERN);
    }
  });

  it("folds German rather than dropping it", () => {
    // "Überschrift" losing its first letter would still be a valid slug, which
    // is exactly why this is asserted: the failure looks like success.
    expect(componentSlug("Überschrift")).toBe("uberschrift");
    expect(componentSlug("Größe")).toBe("grosse");
    expect(componentSlug("Änderung")).toBe("anderung");
  });

  it("spells & as `and`, so two names cannot collide on a hyphen", () => {
    expect(componentSlug("Heading & Separator")).toBe("heading-and-separator");
    // Without the `&` rule both of these would be "heading-separator".
    expect(componentSlug("Heading Separator")).not.toBe(componentSlug("Heading & Separator"));
  });

  it("returns nothing when nothing can survive, rather than an invalid slug", () => {
    // The caller must treat this as invalid input. Sending "" to the database
    // would be answered by a check constraint, in Postgres' words, not ours.
    expect(componentSlug("!!!")).toBe("");
    expect(componentSlug("   ")).toBe("");
  });
});

describe("the generated registry", () => {
  const seed = readFileSync(SEED, "utf8");
  const rows = [
    ...seed.matchAll(/\('((?:[^']|'')*)'\s*,\s*'([a-z0-9-]+)'\s*,\s*'(react|spfx)'\s*,/g),
  ].map(([, name, slug, kind]) => ({ name: name.replace(/''/g, "'"), slug, kind }));

  it("was generated, and has rows", () => {
    expect(seed).toContain("GENERATED by scripts/sync-evim-components.mjs");
    expect(rows.length).toBeGreaterThan(30);
  });

  it("every slug is the one componentSlug would produce for its name", () => {
    // The seed generator has its own copy of the slug rule. If the two ever
    // disagree, a component added in the app and the same component synced from
    // the delivery repo become two rows, and the history splits in half.
    for (const row of rows) {
      expect(componentSlug(row.name), row.name).toBe(row.slug);
    }
  });

  it("has no duplicate slugs — the table's unique constraint, checked early", () => {
    const seen = new Set(rows.map((row) => row.slug));
    expect(seen.size).toBe(rows.length);
  });
});
